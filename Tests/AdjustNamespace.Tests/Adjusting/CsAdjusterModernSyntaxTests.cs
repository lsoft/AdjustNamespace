    /// <summary>
    /// The features of C# 10 - 14 which write a type name at a new position or import a
    /// namespace in a new way. In every test <c>A.B.Cat</c> moves into <c>X.Y</c>.
    /// The extension members of C# 14 are in <c>CsAdjusterExtensionMemberTests</c>,
    /// the unions of C# 15 are in <c>CsAdjusterUnionTests</c>.
    /// </summary>
    public class CsAdjusterModernSyntaxTests
    {
        private const string CatBody =
@"namespace A.B
{
    public class Cat { }
}
";

        /// <summary>
        /// C# 10: the namespace is imported by a <c>global using</c> of another file and the
        /// moved type was the last one of it. The global clause names a namespace which does
        /// not exist anymore (CS0246) unless it is removed.
        /// </summary>
        [Fact]
        public async Task A_global_using_of_an_emptied_namespace_is_removed()
        {
            using var solution = new TestSolution()
                .AddProject("MyApp")
                .AddDocument("MyApp", "Cat.cs", CatBody)
                .AddDocument("MyApp", "GlobalUsings.cs",
@"global using A.B;
")
                .AddDocument("MyApp", "Consumer.cs",
@"namespace Other
{
    public class Consumer
    {
        public Cat Create() => new Cat();
    }
}
")
                ;

            Assert.Empty(await solution.CompilationErrorsAsync());

            await AdjustAndCleanupAsync(solution, "MyApp", "Cat.cs", "X.Y");

            Assert.Contains("using X.Y;", solution.TextOf("MyApp", "Consumer.cs"));
            Assert.DoesNotContain("A.B", solution.TextOf("MyApp", "GlobalUsings.cs"));
            Assert.Empty(await solution.CompilationErrorsAsync());
        }

        /// <summary>
        /// C# 10: the same, but the namespace keeps another type, so the global clause stays
        /// and the consumer gets a using clause of the target namespace.
        /// </summary>
        [Fact]
        public async Task A_global_using_of_a_living_namespace_stays()
        {
            using var solution = new TestSolution()
                .AddProject("MyApp")
                .AddDocument("MyApp", "Cat.cs", CatBody)
                .AddDocument("MyApp", "Dog.cs",
@"namespace A.B
{
    public class Dog { }
}
")
                .AddDocument("MyApp", "GlobalUsings.cs",
@"global using A.B;
")
                .AddDocument("MyApp", "Consumer.cs",
@"namespace Other
{
    public class Consumer
    {
        public Cat Create() => new Cat();

        public Dog Other() => new Dog();
    }
}
")
                ;

            Assert.Empty(await solution.CompilationErrorsAsync());

            await AdjustAndCleanupAsync(solution, "MyApp", "Cat.cs", "X.Y");

            Assert.Contains("using X.Y;", solution.TextOf("MyApp", "Consumer.cs"));
            Assert.Contains("global using A.B;", solution.TextOf("MyApp", "GlobalUsings.cs"));
            Assert.Empty(await solution.CompilationErrorsAsync());
        }

        /// <summary>
        /// .NET 6 implicit usings: a <c>&lt;Using Include="A.B" /&gt;</c> item of the project
        /// file becomes <c>global using global::A.B;</c> of a generated file in <c>obj</c>.
        /// That file is regenerated from the project file on every build, so it must not be
        /// edited; once the namespace is emptied the project does not compile (CS0246) until
        /// the item is removed from the project file, which the adjusting does not touch.
        ///
        /// So the file is not moved (<c>AdjustBlockKind.NamespaceImportedByProjectFile</c>),
        /// rather than the cleanup removing the clause from the generated file: the solution
        /// would compile right after the run and break on the next build. The consumer below
        /// needs nothing else, it sees the type through the generated clause.
        /// </summary>
        [Fact]
        public async Task A_namespace_imported_by_the_project_file_is_not_emptied_silently()
        {
            using var solution = new TestSolution()
                .AddProject("MyApp")
                .AddDocument("MyApp", "Cat.cs", CatBody)
                .AddDocument("MyApp", @"obj\Debug\net8.0\MyApp.GlobalUsings.g.cs",
@"// <auto-generated/>
global using global::A.B;
global using global::System;
")
                .AddDocument("MyApp", "Consumer.cs",
@"namespace Other
{
    public class Consumer
    {
        public Cat Create() => new Cat();
    }
}
")
                ;

            Assert.Empty(await solution.CompilationErrorsAsync());

            await AdjustAndCleanupAsync(solution, "MyApp", "Cat.cs", "X.Y");

            Assert.Contains("namespace A.B", solution.TextOf("MyApp", "Cat.cs"));
            Assert.Contains(
                "global using global::A.B;",
                solution.TextOf("MyApp", @"obj\Debug\net8.0\MyApp.GlobalUsings.g.cs")
                );
            Assert.Empty(await solution.CompilationErrorsAsync());
        }

