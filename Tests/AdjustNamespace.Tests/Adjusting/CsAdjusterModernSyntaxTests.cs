        /// <summary>
        /// C# 10: a lambda with an explicit return type.
        /// </summary>
        [Fact]
        public async Task A_lambda_return_type_is_fixed()
        {
            using var solution = new TestSolution()
                .AddProject("MyApp")
                .AddDocument("MyApp", "Cat.cs", CatBody)
                .AddDocument("MyApp", "Consumer.cs",
@"using A.B;

namespace Other
{
    public class Consumer
    {
        public object Short()
        {
            var make = Cat () => new Cat();
            return make;
        }

        public object Qualified()
        {
            var make = A.B.Cat () => new A.B.Cat();
            return make;
        }
    }
}
")
                ;

            Assert.Empty(await solution.CompilationErrorsAsync());

            await AdjustAndCleanupAsync(solution, "MyApp", "Cat.cs", "X.Y");

            var text = solution.TextOf("MyApp", "Consumer.cs");

            Assert.Contains("using X.Y;", text);
            Assert.Contains("X.Y.Cat () => new X.Y.Cat()", text);
            Assert.Empty(await solution.CompilationErrorsAsync());
        }

