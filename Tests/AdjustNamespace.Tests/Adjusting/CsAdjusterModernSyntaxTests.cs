        }

        /// <summary>
        /// C# 12: an alias of any type, here an array and a tuple of a qualified type.
        /// The target of an alias is written with the full name, the other using clauses
        /// do not help it.
        /// </summary>
        [Fact]
        public async Task An_alias_of_any_type_is_fixed()
        {
            using var solution = new TestSolution()
                .AddProject("MyApp")
                .AddDocument("MyApp", "Cat.cs", CatBody)
                .AddDocument("MyApp", "Consumer.cs",
@"using CatArray = A.B.Cat[];
using CatPair = (A.B.Cat, int);
using NamedCatPair = (A.B.Cat Cat, int Count);

namespace Other
{
    public class Consumer
    {
        public CatArray All() => null;

        public CatPair Pair() => default;

        public NamedCatPair Named() => default;
    }
}
")
                ;

            Assert.Empty(await solution.CompilationErrorsAsync());

            await AdjustAndCleanupAsync(solution, "MyApp", "Cat.cs", "X.Y");

            var text = solution.TextOf("MyApp", "Consumer.cs");

            Assert.Contains("using CatArray = X.Y.Cat[];", text);
            Assert.Contains("using CatPair = (X.Y.Cat, int);", text);
            Assert.Contains("using NamedCatPair = (X.Y.Cat Cat, int Count);", text);
            Assert.Empty(await solution.CompilationErrorsAsync());
        }

        /// <summary>
        /// The runtime types a closed class is compiled with. They do not exist in the
        /// reference assemblies of net48, so they are declared as a source file, exactly as
        /// <see cref="TestSolution.UnionSupportBody"/> does it for the unions.
        /// <c>System.*</c> is a special namespace for the extension, so the file is never adjusted.
        /// </summary>
        private const string ClosedSupportBody =
@"namespace System.Runtime.CompilerServices
{
    [AttributeUsage(AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
    public sealed class IsClosedTypeAttribute : Attribute
    {
    }

    [AttributeUsage(AttributeTargets.All, AllowMultiple = true, Inherited = false)]
    public sealed class CompilerFeatureRequiredAttribute : Attribute
    {
        public CompilerFeatureRequiredAttribute(string featureName)
        {
            FeatureName = featureName;
        }

        public string FeatureName { get; }
    }
}
";

        /// <summary>
        /// C# 15: a closed class (a preview feature, enabled here by
        /// <see cref="TestSolution.WithUnionSupport"/> which switches the language version).
        /// Its subclasses have to be declared in the same assembly, which the move does not
        /// change, and a switch over all of them is exhaustive without a discard.
        /// </summary>
        [Fact]
        public async Task A_closed_class_is_moved()
        {
            using var solution = new TestSolution()
                .WithUnionSupport()
                .AddProject("MyApp")
                .AddDocument("MyApp", "Shape.cs",
@"namespace A.B
{
    public closed class Shape { }
}
")
                .AddDocument("MyApp", "Shapes.cs",
@"using A.B;

namespace Other
{
    public class Circle : Shape { }

    public class Square : Shape { }

    public static class ShapeNames
    {
        public static string Of(Shape shape) => shape switch
        {
            Circle => ""circle"",
            Square => ""square"",
        };
    }
}
")
                .AddDocument("MyApp", "ClosedSupport.cs", ClosedSupportBody)
                ;

            Assert.Empty(await solution.CompilationErrorsAsync());

            await AdjustAndCleanupAsync(solution, "MyApp", "Shape.cs", "X.Y");

            var text = solution.TextOf("MyApp", "Shapes.cs");

            Assert.Contains("using X.Y;", text);
            Assert.DoesNotContain("using A.B;", text);
            Assert.Empty(await solution.CompilationErrorsAsync());
        }

